# coding: utf-8
"""一次性：给 chapter00_序章.json 的每条 say 标 emotion（替 chapter-dialoguer，验证 CosyVoice emotion 链路）。

emotion 据台词当下情绪标（酒店=海王调侃；咖啡店=调情；路口=无奈；夹缝=陆择玩世不恭掩盖+伊芙庄严宣告）。
正常流程下 emotion 由 chapter-dialoguer 在创作时标；本脚本仅序章迁移用。
"""
import json

# (scene_id, line_idx) → emotion；未列的兜底"平静"
EMOTION_MAP = {
    ("酒店", 2): "平静", ("酒店", 6): "调侃", ("酒店", 8): "调侃", ("酒店", 9): "调侃",
    ("酒店", 10): "调侃", ("酒店", 12): "调侃", ("酒店", 14): "调侃", ("酒店", 16): "调侃",
    ("酒店", 17): "调侃", ("酒店", 19): "平静", ("酒店", 20): "调侃", ("酒店", 21): "平静",
    ("酒店", 22): "无奈", ("酒店", 23): "无奈", ("酒店", 26): "平静",
    ("咖啡店", 3): "平静", ("咖啡店", 5): "调侃", ("咖啡店", 7): "调侃",
    ("路口", 2): "无奈",
    ("夹缝", 3): "震惊", ("夹缝", 7): "平静", ("夹缝", 8): "平静", ("夹缝", 9): "震惊",
    ("夹缝", 10): "平静", ("夹缝", 11): "平静", ("夹缝", 14): "调侃", ("夹缝", 15): "平静",
    ("夹缝", 16): "平静", ("夹缝", 17): "震惊", ("夹缝", 18): "平静", ("夹缝", 19): "调侃",
    ("夹缝", 20): "调侃", ("夹缝", 21): "平静", ("夹缝", 22): "平静", ("夹缝", 23): "平静",
    ("夹缝", 24): "平静", ("夹缝", 25): "平静", ("夹缝", 26): "平静", ("夹缝", 29): "悲伤",
    ("夹缝", 30): "无奈", ("夹缝", 31): "平静", ("夹缝", 32): "温柔", ("夹缝", 35): "平静",
    ("夹缝", 36): "温柔",
}

PATH = "99_game/data/chapters/chapter00_序章.json"

ch = json.load(open(PATH, encoding="utf-8"))
n = 0
for blk in ch["scenes"]:
    sid = blk["id"]
    for li, line in enumerate(blk["lines"]):
        if line.get("op") == "say":
            line["emotion"] = EMOTION_MAP.get((sid, li), "平静")
            n += 1
json.dump(ch, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print(f"labeled {n} says with emotion")
